'use client';

import Link from 'next/link';
import { ShieldCheck, MapPin, Truck } from 'lucide-react';
import { Product } from '@/types';
import { formatUsd } from '@/lib/currency';
import { useStoreConfigStore } from '@/store/useStoreConfigStore';
import { ProductCard } from './ProductCard';

interface ProductDetailExtraSectionProps {
  product: Product;
  relatedProducts?: Product[];
}

export function ProductDetailExtraSection({
  product,
  relatedProducts = [],
}: ProductDetailExtraSectionProps) {
  const storeConfig = useStoreConfigStore((state) => state.config);
  const shortDeliveryUsd = Number(
    storeConfig?.delivery_corta_usd ?? storeConfig?.delivery_base_usd ?? 1.5
  );
  const maxBoxesMoto = storeConfig?.delivery_max_cajas_motorizado ?? 2;
  const storeAddress = storeConfig?.direccion_fisica || 'C.C. Ciudad Catador Local N1';

  const isAutoGeneratedDesc =
    product.description.startsWith(`${product.name} • `) &&
    product.description.includes('(');
  const presentationText =
    product.saleMode === 'solo_caja'
      ? 'por caja cerrada'
      : product.saleMode === 'solo_unidad'
      ? 'por unidad'
      : 'por unidad al detal o por caja cerrada';
  const displayDescription = isAutoGeneratedDesc
    ? `Disponible ${presentationText} en la categoría ${product.category} con inventario verificado en tiempo real en EL CATADOR. Barinas.`
    : product.description;

  return (
    <div className="space-y-6 sm:space-y-8 pt-2 sm:pt-4 min-w-0 max-w-full">
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-4 sm:gap-5 items-stretch">
        <section className="lg:col-span-7 rounded-2xl bg-white border border-slate-100 sm:border-slate-200 shadow-sm p-4 sm:p-6 flex flex-col justify-between gap-4">
          <div className="space-y-2">
            <h2 className="text-sm sm:text-base font-black text-slate-900">Detalles del producto</h2>
            <p className="text-[13px] sm:text-sm text-slate-600 leading-relaxed whitespace-pre-line">
              {displayDescription}
            </p>
          </div>

          <div className="hidden sm:flex flex-wrap items-center gap-2 pt-3 border-t border-slate-100 text-xs font-bold text-slate-700">
            <span className="inline-flex items-center gap-1.5 rounded-full bg-[#F7F8FA] border border-slate-200 px-3 py-1.5">
              <ShieldCheck className="h-4 w-4 text-emerald-600 shrink-0" />
              100% Original y Precintado
            </span>
            <span className="inline-flex items-center gap-1.5 rounded-full bg-[#F7F8FA] border border-slate-200 px-3 py-1.5">
              <Truck className="h-4 w-4 text-catador-amber shrink-0" />
              Motorizado hasta {maxBoxesMoto} {maxBoxesMoto === 1 ? 'caja' : 'cajas'} · Carga mayorista
            </span>
          </div>
        </section>

        <section className="lg:col-span-5 rounded-2xl bg-white border border-slate-100 sm:border-slate-200 shadow-sm p-4 sm:p-6 flex flex-col justify-between gap-4">
          <div className="space-y-3">
            <div className="flex items-center justify-between gap-2">
              <div>
                <h2 className="text-base font-black text-slate-900">Entrega en Barinas</h2>
                <p className="text-xs text-slate-500 mt-0.5 truncate max-w-[280px]" title={storeAddress}>
                  Sede: {storeAddress}
                </p>
              </div>
              <span className="h-8 w-8 shrink-0 rounded-full bg-catador-amber-soft border border-catador-amber-oak/60 flex items-center justify-center text-catador-blue">
                <MapPin className="h-4 w-4" />
              </span>
            </div>

            <div className="rounded-xl bg-[#F7F8FA] border border-slate-200/80 divide-y divide-slate-200/80 text-xs tabular-nums">
              <div className="flex justify-between gap-3 px-3 py-2">
                <span className="text-slate-600 font-semibold">Retiro Pick-Up en Bodegón</span>
                <strong className="text-emerald-700 shrink-0">Gratis</strong>
              </div>
              <div className="flex justify-between gap-3 px-3 py-2">
                <span className="text-slate-600 font-semibold">Delivery GPS Corta (0–3 km)</span>
                <strong className="text-slate-900 shrink-0">{formatUsd(shortDeliveryUsd)} USD</strong>
              </div>
              <div className="flex justify-between gap-3 px-3 py-2">
                <span className="text-slate-600 font-semibold">Métodos de pago</span>
                <strong className="text-slate-900 text-right">Pago Móvil · Zelle · Efectivo</strong>
              </div>
            </div>
          </div>

          <Link
            href="/carrito#cotizar-delivery"
            className="w-full min-h-[40px] flex items-center justify-center rounded-full border border-catador-blue text-catador-blue hover:bg-catador-blue hover:text-white text-xs font-extrabold transition-colors"
          >
            Cotizar delivery
          </Link>
        </section>
      </div>

      {relatedProducts.length > 0 && (
        <section className="space-y-3.5 sm:space-y-4">
          <div className="border-l-4 border-catador-amber pl-3">
            <h2 className="text-base sm:text-xl font-black text-slate-900 tracking-tight truncate">
              Completa tu combo en {product.category}
            </h2>
          </div>
          <div className="flex overflow-x-auto snap-x snap-mandatory gap-2.5 pb-1 scrollbar-none sm:grid sm:grid-cols-3 lg:grid-cols-4 xl:grid-cols-5 sm:gap-3.5 sm:pb-0">
            {relatedProducts.slice(0, 5).map((rel) => (
              <ProductCard
                key={rel.id}
                product={rel}
                isCompact
                className="w-[46vw] min-w-[168px] max-w-[205px] shrink-0 snap-start sm:w-auto sm:min-w-0 sm:max-w-none"
              />
            ))}
          </div>
        </section>
      )}
    </div>
  );
}
